#!/usr/bin/env python3
"""Generate the frontend TypeScript SDK from the checked-in Go OpenAPI contract."""

from __future__ import annotations

import copy
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
ADMIN = ROOT / "frontend" / "admin"
SOURCE = ROOT / "backend" / "server" / "docs" / "openapi.json"
TEMP_SPEC = ADMIN / "openapi.json"
SDK_DIR = ADMIN / "src" / "lib" / "sdk"
HTTP_METHODS = {"get", "post", "put", "patch", "delete", "head", "options", "trace"}


def flatten_response_envelopes(spec: dict[str, Any]) -> int:
    """Present business payloads to Orval; the runtime mutator unwraps the same envelope."""
    count = 0
    schemas = (spec.get("components") or {}).get("schemas") or {}
    for path, path_item in (spec.get("paths") or {}).items():
        for method, operation in path_item.items():
            if method not in HTTP_METHODS or not isinstance(operation, dict):
                continue
            for response in (operation.get("responses") or {}).values():
                for media in ((response or {}).get("content") or {}).values():
                    schema = media.get("schema") if isinstance(media, dict) else None
                    if isinstance(schema, dict) and isinstance(schema.get("$ref"), str):
                        ref = schema["$ref"]
                        prefix = "#/components/schemas/"
                        if ref.startswith(prefix):
                            schema = schemas.get(ref[len(prefix):])
                    properties = schema.get("properties") if isinstance(schema, dict) else None
                    if not isinstance(properties, dict) or not {"code", "msg", "data"}.issubset(properties):
                        continue
                    payload = copy.deepcopy(properties["data"])
                    if not isinstance(payload, dict) or not any(key in payload for key in ("type", "$ref", "oneOf", "anyOf", "allOf", "items")):
                        payload = {"type": "object"}
                    media["schema"] = payload
                    count += 1
    return count


def warn_inline_data_wrappers(spec: dict[str, Any]) -> None:
    offenders: list[str] = []
    for path, path_item in (spec.get("paths") or {}).items():
        for method, operation in path_item.items():
            if method not in HTTP_METHODS or not isinstance(operation, dict):
                continue
            for response in (operation.get("responses") or {}).values():
                for media in ((response or {}).get("content") or {}).values():
                    schema = media.get("schema") if isinstance(media, dict) else None
                    properties = schema.get("properties") if isinstance(schema, dict) else None
                    if not isinstance(properties, dict) or "data" not in properties:
                        continue
                    if set(properties).issubset({"data", "pagination", "meta"}):
                        offenders.append(f"{method.upper()} {path} ({operation.get('operationId', '?')})")
    if offenders:
        print("Warning: possible inline data wrappers may not match the runtime envelope unwrapping:")
        for offender in offenders:
            print(f"  - {offender}")


def make_operation_ids_unique(spec: dict[str, Any]) -> None:
    seen: set[str] = set()
    operations = [
        (method, operation)
        for path_item in (spec.get("paths") or {}).values()
        for method, operation in path_item.items()
        if method in HTTP_METHODS and isinstance(operation, dict)
    ]
    reserved = {op["operationId"] for _, op in operations if op.get("operationId")}
    for method, operation in operations:
        operation_id = operation.get("operationId")
        if not operation_id:
            raise ValueError("Every API operation must define operationId")
        if operation_id not in seen:
            seen.add(operation_id)
            continue
        base = f"{operation_id}{method.capitalize()}"
        candidate = base
        suffix = 2
        while candidate in reserved or candidate in seen:
            candidate = f"{base}{suffix}"
            suffix += 1
        operation["operationId"] = candidate
        seen.add(candidate)


def write_barrel() -> None:
    generated = sorted(
        path.stem
        for path in SDK_DIR.glob("*.ts")
        if path.stem not in {"index", "sdk.schemas", "sdk"}
    )
    lines = [
        "// Generated by make gen-sdk. Do not edit manually.",
        "export * from './sdk.schemas';",
        *(f"export * from './{name}';" for name in generated),
    ]
    (SDK_DIR / "index.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")


def normalize_generated_files() -> None:
    for path in SDK_DIR.glob("*.ts"):
        path.write_text(path.read_text(encoding="utf-8").rstrip() + "\n", encoding="utf-8")


def main() -> int:
    if not SOURCE.exists():
        raise SystemExit(f"OpenAPI contract not found: {SOURCE}")
    with SOURCE.open(encoding="utf-8") as file:
        spec = json.load(file)

    try:
        node_version = subprocess.check_output(["node", "--version"], text=True).strip()
    except FileNotFoundError:
        raise SystemExit("SDK generation requires Node.js >= 22.18.0.") from None
    match = re.fullmatch(r"v(\d+)\.(\d+)\.(\d+)", node_version)
    if not match or tuple(map(int, match.groups())) < (22, 18, 0):
        raise SystemExit(f"Orval 8.43.0 requires Node.js >= 22.18.0; found {node_version}.")

    flattened = flatten_response_envelopes(spec)
    warn_inline_data_wrappers(spec)
    make_operation_ids_unique(spec)
    TEMP_SPEC.write_text(json.dumps(spec, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"OpenAPI: {SOURCE}")
    print(f"Flattened response envelopes: {flattened}")

    try:
        result = subprocess.run(["npm", "exec", "--", "orval", "--config", "orval.config.ts"], cwd=ADMIN, check=False)
        if result.returncode:
            return result.returncode
        normalize_generated_files()
        write_barrel()
        result = subprocess.run(["npm", "exec", "--", "tsc", "--noEmit"], cwd=ADMIN, check=False)
        return result.returncode
    finally:
        TEMP_SPEC.unlink(missing_ok=True)


if __name__ == "__main__":
    sys.exit(main())
